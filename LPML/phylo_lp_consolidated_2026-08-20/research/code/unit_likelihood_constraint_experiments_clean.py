#!/usr/bin/env python3
"""
Clean research harness for topology-independent / unit-structure likelihood bounds.

Uses the fixed-flow unit library structure generated by fixed_flow_unit_generator.py.
No integer variables and no subtree enumeration are used to construct the bounds.
For L=8, exact topology enumeration is available only as a benchmark.

Core ideas implemented here:
  1. Exact count scaling: Lhat_m = L_m / beta**m.
  2. Composition-restricted dynamic-programming boxes indexed only by
     (descendant count, A/C/G/T count tuple), not topology.
  3. Root split-aware cuts keyed directly to a root split unit m=a+b.
  4. Optional stress test across every 8-leaf base composition.
"""
from __future__ import annotations

import argparse
import importlib.util
import itertools
import json
import math
from collections import defaultdict
from pathlib import Path
from typing import Dict, Iterable, List, Tuple

import numpy as np
import pandas as pd
from scipy.linalg import expm

BASES = "ACGT"
BASE_INDEX = {b: i for i, b in enumerate(BASES)}

# Deliberately asymmetric stationary GTR-like model: tests do not rely on JC69 symmetry.
PI = np.array([0.30, 0.20, 0.25, 0.25], dtype=float)
R = np.array(
    [
        [0.0, 1.00, 2.00, 0.55],
        [1.00, 0.0, 0.75, 1.35],
        [2.00, 0.75, 0.0, 0.90],
        [0.55, 1.35, 0.90, 0.0],
    ],
    dtype=float,
)
Q = np.zeros((4, 4), dtype=float)
for i in range(4):
    for j in range(4):
        if i != j:
            Q[i, j] = R[i, j] * PI[j]
for i in range(4):
    Q[i, i] = -Q[i].sum()
Q /= -float(PI @ np.diag(Q))


def transition_for_count(m: int) -> np.ndarray:
    """Test branch matrix depending only on known descendant flow m."""
    t = 0.10 if m == 1 else 0.055 + 0.018 * math.log2(m)
    return expm(Q * t)


P1 = transition_for_count(1)
BETA = float(P1.max())


def scaled_leaf_vector(base: str) -> np.ndarray:
    return P1[:, BASE_INDEX[base]] / BETA


def merge_signal(x: np.ndarray, y: np.ndarray, m: int) -> np.ndarray:
    """Scaled post-edge message for a count-m subtree from two child messages."""
    # beta**a * beta**b / beta**(a+b) = 1, so no scale coefficient is needed.
    return transition_for_count(m) @ (x * y)


Composition = Tuple[int, int, int, int]
Box = np.ndarray  # shape (4,2): [lower,upper] for A,C,G,T coordinates


def build_composition_boxes_restricted(global_counts: Composition):
    """
    Topology-independent component boxes for every feasible sub-composition c <= global_counts.

    State: (m,c), where m=sum(c).  The DP unions over all binary split sizes and all
    child composition partitions.  It never stores topology or leaf identity.
    """
    g = tuple(int(x) for x in global_counts)
    L = sum(g)
    leaf = np.array([scaled_leaf_vector(b) for b in BASES])

    out: Dict[Tuple[int, Composition], Box] = {}
    partial: Dict[Tuple[int, Composition], Box] = {}
    by_size: Dict[int, List[Composition]] = defaultdict(list)

    for b in range(4):
        if g[b] > 0:
            c = tuple(1 if i == b else 0 for i in range(4))
            out[(1, c)] = np.stack([leaf[b], leaf[b]], axis=1)
            by_size[1].append(c)

    for m in range(2, L + 1):
        acc_out = {}
        acc_partial = {}
        Pm = transition_for_count(m)

        for a in range(1, m // 2 + 1):
            b = m - a
            if not by_size[a] or not by_size[b]:
                continue
            for c1 in by_size[a]:
                B1 = out[(a, c1)]
                lo1, hi1 = B1[:, 0], B1[:, 1]
                for c2 in by_size[b]:
                    c = tuple(c1[i] + c2[i] for i in range(4))
                    if any(c[i] > g[i] for i in range(4)):
                        continue
                    B2 = out[(b, c2)]
                    zlo = lo1 * B2[:, 0]
                    zhi = hi1 * B2[:, 1]
                    olo = Pm @ zlo
                    ohi = Pm @ zhi

                    if c not in acc_out:
                        acc_out[c] = [olo.copy(), ohi.copy()]
                        acc_partial[c] = [zlo.copy(), zhi.copy()]
                    else:
                        acc_out[c][0] = np.minimum(acc_out[c][0], olo)
                        acc_out[c][1] = np.maximum(acc_out[c][1], ohi)
                        acc_partial[c][0] = np.minimum(acc_partial[c][0], zlo)
                        acc_partial[c][1] = np.maximum(acc_partial[c][1], zhi)

        by_size[m] = list(acc_out)
        for c, (lo, hi) in acc_out.items():
            out[(m, c)] = np.stack([lo, hi], axis=1)
        for c, (lo, hi) in acc_partial.items():
            partial[(m, c)] = np.stack([lo, hi], axis=1)

    return out, partial


def root_split_upper(global_counts: Composition, out_boxes, split_a: int):
    """
    Upper bound for a root unit whose physical split is L=split_a+(L-split_a).

    Keeps the four root states together for each child-composition partition, then
    maximizes over partitions. This is stronger than summing four independently
    maximized state-coordinate bounds.
    """
    g = tuple(int(x) for x in global_counts)
    L = sum(g)
    a = min(int(split_a), L - int(split_a))
    b = L - a

    by_size = defaultdict(list)
    for m, c in out_boxes:
        by_size[m].append(c)

    best = -math.inf
    arg = None
    for c1 in by_size[a]:
        c2 = tuple(g[i] - c1[i] for i in range(4))
        if min(c2) < 0 or (b, c2) not in out_boxes:
            continue
        hi1 = out_boxes[(a, c1)][:, 1]
        hi2 = out_boxes[(b, c2)][:, 1]
        value = float(PI @ (hi1 * hi2))
        if value > best:
            best = value
            arg = (c1, c2)
    return best, arg


def root_candidate_cuts(library_json: Path, global_counts: Composition):
    """Return a linear upper coefficient U_r for each root candidate r."""
    lib = json.loads(Path(library_json).read_text())
    out, _ = build_composition_boxes_restricted(global_counts)
    rows = []
    for uid in lib["root_candidates"]:
        u = lib["units"][uid]
        a = int(u["split_a"])
        ub, arg = root_split_upper(global_counts, out, a)
        rows.append(
            {
                "root_unit": uid,
                "split_a": a,
                "split_b": int(u["split_b"]),
                "scaled_likelihood_upper": ub,
                "arg_child_compositions": str(arg),
            }
        )
    return pd.DataFrame(rows)


def exact_best_8(pattern: str) -> float:
    """Exact topology benchmark only; not used to construct the LP bounds."""
    if len(pattern) != 8:
        raise ValueError("exact_best_8 is benchmark-only for 8 leaves")
    n = 8
    leaf = [scaled_leaf_vector(b) for b in pattern]
    memo = {1 << i: [leaf[i]] for i in range(n)}

    for size in range(2, n):
        for mask in range(1, 1 << n):
            if mask.bit_count() != size:
                continue
            first = mask & -mask
            arr = []
            s = (mask - 1) & mask
            while s:
                A, B = s, mask ^ s
                if B and (A & first) and A < B:
                    for x in memo[A]:
                        for y in memo[B]:
                            arr.append(merge_signal(x, y, size))
                s = (s - 1) & mask
            memo[mask] = arr

    full = (1 << n) - 1
    best = -1.0
    s = (full - 1) & full
    first = full & -full
    while s:
        A, B = s, full ^ s
        if B and (A & first) and A < B:
            for x in memo[A]:
                for y in memo[B]:
                    best = max(best, float(PI @ (x * y)))
        s = (s - 1) & full
    return best


def all_compositions(L: int) -> Iterable[Composition]:
    for a in range(L + 1):
        for c in range(L - a + 1):
            for g in range(L - a - c + 1):
                yield (a, c, g, L - a - c - g)


def stress_8() -> pd.DataFrame:
    rows = []
    for counts in all_compositions(8):
        pattern = "".join(b * n for b, n in zip(BASES, counts))
        out, _ = build_composition_boxes_restricted(counts)
        ub = max(root_split_upper(counts, out, a)[0] for a in range(1, 5))
        exact = exact_best_8(pattern)
        rows.append(
            {
                "A": counts[0],
                "C": counts[1],
                "G": counts[2],
                "T": counts[3],
                "distinct": sum(x > 0 for x in counts),
                "exact_scaled": exact,
                "splitaware_upper": ub,
                "upper_exact_ratio": ub / exact,
            }
        )
    return pd.DataFrame(rows)


def parse_counts(text: str) -> Composition:
    vals = tuple(int(x) for x in text.split(","))
    if len(vals) != 4 or min(vals) < 0:
        raise argparse.ArgumentTypeError("counts must be four nonnegative integers A,C,G,T")
    return vals  # type: ignore[return-value]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--library-json", type=Path)
    ap.add_argument("--counts", type=parse_counts, default=(2, 2, 2, 2))
    ap.add_argument("--out", type=Path, default=Path("/mnt/data/root_candidate_likelihood_cuts.csv"))
    ap.add_argument("--stress-8", action="store_true")
    args = ap.parse_args()

    print(f"beta={BETA:.16g}")
    print("Scaling: Lhat_m = L_m / beta^m; split coefficient is exactly 1.")

    if args.library_json:
        df = root_candidate_cuts(args.library_json, args.counts)
        df.to_csv(args.out, index=False)
        print(df.to_string(index=False))
        print(f"wrote {args.out}")

    if args.stress_8:
        df = stress_8()
        path = Path("/mnt/data/composition_splitaware_all_8leaf_clean.csv")
        df.to_csv(path, index=False)
        print(df.groupby("distinct")["upper_exact_ratio"].agg(["count", "median", "mean", "max"]))
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
